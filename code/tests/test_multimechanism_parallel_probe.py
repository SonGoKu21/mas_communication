def offline_expiring_worker():
    import os
    import signal
    import time
    from mas_faults.llm_client import request_deadline
    handler = signal.getsignal(signal.SIGALRM)
    started = time.monotonic()
    try:
        with request_deadline(1):
            time.sleep(3)
    except TimeoutError:
        return {"pid": os.getpid(), "expired": True, "elapsed": time.monotonic() - started,
                "restored": signal.getsignal(signal.SIGALRM) == handler and signal.getitimer(signal.ITIMER_REAL) == (0, 0)}
    return {"pid": os.getpid(), "expired": False}


def test_spawn_deadline_actually_expires_and_worker_is_reusable(probe):
    with probe._process_pool(max_workers=1) as pool:
        expired = pool.submit(offline_expiring_worker).result(timeout=10)
        reused = pool.submit(offline_spawn_worker, "still healthy").result(timeout=10)
    assert expired["expired"] is True and expired["restored"] is True
    assert 0 < expired["elapsed"] < 3
    assert reused == ("still healthy", expired["pid"], True)
