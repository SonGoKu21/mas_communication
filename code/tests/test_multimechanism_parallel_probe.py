    assert [(b["round"], b["mode"]) for b in result["batches"]] == [(1, "sequential"), (1, "parallel"), (2, "parallel"), (2, "sequential")]
    assert [b["wall_seconds"] for b in result["batches"]] == [10, 5, 4, 8]
    assert len(seen) == len({s["trial_id"] for s in seen}) == 8
    assert len({s["ledger_path"] for s in seen}) == 8
    assert all(s["job"]["arm"] == "baseline" and s["job"]["condition"] == "clean" for s in seen)
    assert [r["speedup"] for r in result["rounds"]] == [2, 2]
    assert result["passed"] is True


