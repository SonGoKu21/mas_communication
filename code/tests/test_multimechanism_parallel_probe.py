    def run(spec):
        seen.append(spec)
        if spec["mode"] == "parallel":
            barrier.wait(timeout=3)
        return unit_result(spec)
    def pool(max_workers):
        widths.append(max_workers)
        return ThreadPoolExecutor(max_workers=max_workers)
    result = probe.run_batches(TASKS, tmp_path, {}, "http://127.0.0.1:17770", "sequential",
                               trial_runner=run, pool_factory=pool, clock=lambda: next(clock))
