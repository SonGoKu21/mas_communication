class UnitSession:
    """Fake responses only: receipts are generated by the actual executor."""
    def __init__(self, identity, shared):
        self.identity, self.shared, self.quantity = identity, shared, 0
        self.updated = False

    def response(self, url, data=None, text=None):
        body = text if text is not None else json.dumps(data)
        return SimpleNamespace(status_code=200, url=url, text=body, content=body.encode(),
                               json=lambda: data, raise_for_status=lambda: None)

    def item(self):
        quantity = self.shared.get("quantity", self.quantity) if self.shared is not None else self.quantity
        return {"item_id": 17, "sku": "TEA", "name": "Tea", "qty": quantity}

    def get(self, url, **kwargs):
        if "/guest-carts/" in url:
            return self.response(url, [self.item()])
        return self.response(url, text='<input name="product" value="12"><div data-product-sku="TEA">')

    def post(self, url, **kwargs):
        if url.endswith("/guest-carts"):
            return self.response(url, str(self.identity))
        self.quantity += kwargs["json"]["cartItem"]["qty"]
        if self.updated and self.shared is not None:
            self.shared["quantity"] = self.quantity
        return self.response(url, self.item())

    def put(self, url, **kwargs):
        self.quantity = kwargs["json"]["cartItem"]["qty"]
        if self.shared is not None:
            self.shared["quantity"] = self.quantity
        return self.response(url, self.item())

    def close(self):
        pass


class UnitExecutor(MultiStateShoppingExecutor):
    """Real adapter with injected HTTP; not proof of Magento semantics."""
    def __init__(self, identity, trace, *, shared=None):
        super().__init__("http://127.0.0.1:17770")
        self.session.close()
        self.session = UnitSession(identity, shared)
        self.identity, self.trace = identity, trace

    def add_to_cart(self, task):
        self.trace.append((self.identity, "INIT"))
        return super().add_to_cart(task)

    def add_quantity(self, task, quantity):
        self.trace.append((self.identity, "POST"))
        self.session.updated = True
        return super().add_quantity(task, quantity)

    def set_quantity(self, task, quantity):
        self.trace.append((self.identity, "PUT"))
        self.session.updated = True
        return super().set_quantity(task, quantity)

    def reobserve_cart(self, task):
        self.trace.append((self.identity, "GET"))
        return super().reobserve_cart(task)


def executor_factory(*, same_cart=False, cross_talk=False):
    instances, trace, shared = [], [], {} if cross_talk else None
    lock = Lock()

    def create(base):
        with lock:
            executor = UnitExecutor(0 if same_cart else len(instances), trace, shared=shared)
            instances.append(executor)
            return executor
    return create, instances, trace


